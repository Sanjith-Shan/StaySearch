"""Builds NUMBERS.md from results/*.jsonl: every figure in it is read from a results row, and each
table names the file it came from. Run after the experiments; never edit NUMBERS.md by hand.
"""
from __future__ import annotations

import glob
import json
from collections import defaultdict
from pathlib import Path

from staysearch.config import RESULTS, ROOT


def rows(name: str) -> list[dict]:
    out = []
    for p in sorted(glob.glob(str(RESULTS / f"{name}*.jsonl"))):
        for line in open(p):
            if line.strip():
                d = json.loads(line)
                d["_file"] = "results/" + Path(p).name
                out.append(d)
    return out


def pct(x, d=1):
    return "n/a" if x is None else f"{100 * x:.{d}f}%"


def ci(r, k):
    c = r.get(f"{k}_ci95")
    return f"{pct(r[k])} [{pct(c[0])}, {pct(c[1])}]" if c else pct(r.get(k))


def machine(r) -> str:
    m = r.get("machine", {})
    ld = r.get("load", r.get("load_start", {}))
    la = ld.get("loadavg_1m", ld.get("loadavg1", ld.get("cpu_percent", "?"))) if isinstance(ld, dict) else ld
    return f"{m.get('cpu', m.get('cpuBrand', '?'))}, load {la}"


def table(header: list[str], body: list[list]) -> str:
    s = "| " + " | ".join(header) + " |\n|" + "---|" * len(header) + "\n"
    return s + "".join("| " + " | ".join(str(c) for c in r) + " |\n" for r in body)


def main() -> None:
    md = ["# NUMBERS", "",
          "Every measured figure in this repo, generated by `python -m staysearch.numbers` from `results/*.jsonl`.",
          "Each section names its source file; every row in those files carries the machine and its load.",
          "Rows marked SIMULATED come from simulated logs and are never quoted as anything else.", ""]
    # M0
    m0 = rows("m0_data")
    tot = [r for r in m0 if r.get("kind") == "total"]
    if tot:
        t = tot[-1]
        cities = [r for r in m0 if r.get("kind") == "city"]
        md += ["## M0: data (`results/m0_data.jsonl`)", "",
               f"- Cities: {len(cities)}; reviews: {t['reviews_total']:,}; distinct reviewers: {t['reviewers_total']:,}",
               f"- Reviewers appearing in more than one city: {t['cross_city_reviewers_total']:,} ({pct(t['cross_city_reviewers_total'] / t['reviewers_total'])})",
               f"- Reviewed stays kept (all splits): {t['queries_total']:,}; trips: {t['trips']:,}; single-stay trips: {pct(t['trips_single_review_share'])}",
               f"- Update stream events (S3 to S4): {t['update_events_total']:,}", ""]
        body = []
        for r in cities:
            l = r["labels"]
            sn = r["snapshots"]
            u = r["update_stream"]
            body.append([r["city"], f"{sn['S3']['listings_after_parse']:,}", f"{sn['S4']['listings_after_parse']:,}",
                         f"{l.get('test_kept', 0):,}", f"{l.get('test_drop_closed_in_snapshot', 0):,}",
                         f"{l.get('test_drop_not_in_snapshot', 0):,}", f"{l.get('cross_city_reviewers', 0):,}",
                         f"{u.get('avail_events', 0):,}", f"{u.get('price_events', 0):,}", f"{u.get('new_listing_events', 0):,}"])
        md += [table(["city", "listings S3", "listings S4", "test kept", "test dropped: closed at S3",
                      "test dropped: not in S3", "cross-city reviewers", "avail events", "price events", "new listings"], body), ""]
    # Retrieval
    ret = rows("m1_baselines") + rows("m2_retrieval")
    if ret:
        md += ["## exp1, exp2, exp8: retrieval of the reviewed stay (test split, point-in-time eligible sets)", "",
               "Exact scoring over each query's eligible set; 95% bootstrap intervals; same 20,000-query stratified sample for every row.", ""]
        for sl in ("all", "with_history"):
            body = []
            for r in ret:
                if r.get("split") == "test" and r.get("slice") == sl:
                    body.append([r["model"], r.get("exp"), ci(r, "recall@10"), ci(r, "recall@100"), ci(r, "recall@500"),
                                 ci(r, "ndcg@10"), r["n_queries"], r.get("eligible_median"), r["_file"]])
            if body:
                md += [f"**Slice: {sl}**", "", table(["model", "exp", "recall@10", "recall@100", "recall@500", "NDCG@10",
                                                      "queries", "median eligible", "file"], body), ""]
        city_rows = defaultdict(dict)
        for r in ret:
            if r.get("split") == "test" and str(r.get("slice", "")).startswith("city="):
                city_rows[r["slice"][5:]][r["model"]] = r["recall@100"]
        if city_rows:
            models = sorted({m for v in city_rows.values() for m in v})
            md += ["**Recall@100 per city (test)**", "",
                   table(["city", *models], [[c, *[pct(v.get(m)) for m in models]] for c, v in sorted(city_rows.items())]), ""]
    tr = rows("m2_training")
    if tr:
        md += ["## M2 training runs (`results/m2_training*.jsonl`)", "",
               table(["name", "sampler", "similarity", "history", "drop guests/nights", "best val recall@100", "file"],
                     [[r["name"], r["sampler"], r["similarity"], r["history"], r["drop_guests_nights"],
                       pct(r["best_val_recall@100"]), r["_file"]] for r in tr]), ""]
    ann = rows("m2_ann")
    if ann:
        md += ["## exp3: clustering and IVF/HNSW recall vs exact (`results/m2_ann.jsonl`)", ""]
        cs = [r for r in ann if r.get("kind") == "cluster_sizes"]
        md += [table(["model", "similarity", "clusters", "largest cluster share", "top-2 share", "Gini", "empty"],
                     [[r["model"], r["similarity"], r["nlist"], pct(r["largest_cluster_share"]), pct(r["top2_share"]),
                       f"{r['gini']:.3f}", r["empty_clusters"]] for r in cs]), ""]
        iv = [r for r in ann if r.get("kind") == "ivf_recall" and r["nlist"] == 128]
        md += ["**IVF, 128 clusters: recall@100 vs exact** (paper column: 2601.06873 Table 2)", "",
               table(["similarity", "nprobe", "unfiltered", "filtered (eligible set)", "share of eligible scanned", "paper"],
                     [[r["similarity"], r["nprobe"], pct(r["recall@100_vs_exact_unfiltered"]),
                       pct(r["recall@100_vs_exact_filtered"]), pct(r["filtered_share_of_eligible_scanned"]),
                       pct(r.get("paper_table2"), 0) if r.get("paper_table2") is not None else ""] for r in iv]), ""]
        hn = [r for r in ann if r.get("kind") == "hnsw_recall"]
        md += ["**FAISS HNSW (M=32): recall@100 vs exact**", "",
               table(["similarity", "efSearch", "unfiltered", "filtered", "us/query unfiltered", "us/query filtered", "bytes/vector"],
                     [[r["similarity"], r["efSearch"], pct(r["recall@100_vs_exact_unfiltered"]), pct(r["recall@100_vs_exact_filtered"]),
                       f"{r['us_per_query_unfiltered']:.0f}", f"{r['us_per_query_filtered']:.0f}", f"{r['bytes_per_vector']:.0f}"] for r in hn]), ""]
        fm = [r for r in ann if r.get("kind") == "faiss_memory_and_removal"]
        for r in fm:
            md += [f"- FAISS memory per vector ({r['similarity']}, {r['n_vectors']:,} x {r['dim']}): IndexIVFFlat "
                   f"{r['ivf_bytes_per_vector']:.0f} B, IndexHNSWFlat {r['hnsw_bytes_per_vector']:.0f} B (raw vector {r['raw_vector_bytes']} B). "
                   f"remove_ids: IVF {r['ivf_flat_remove_ids']}; HNSW {r['hnsw_flat_remove_ids']}"]
        md += [""]
    rk = rows("m4_ranking")
    if rk:
        md += ["## exp6: ranking over the top K (test split) (`results/m4_ranking.jsonl`)", "",
               "NDCG@10 and MRR of the reviewed stay; 0 when retrieval missed it (the positive_in_topK slice conditions on a hit).", ""]
        for sl in ("all", "with_history", "positive_in_topK"):
            body = [[r["model"], ci(r, "ndcg@10"), ci(r, "mrr"), r["n_queries"], pct(r.get("positive_in_topK_share"))]
                    for r in rk if r["slice"] == sl]
            md += [f"**Slice: {sl}**", "", table(["model", "NDCG@10", "MRR", "queries", "positive in top K"], body), ""]
    rr = rows("m4_replay_recall")
    if rr:
        md += ["## exp7: replay recall@100 (`results/m4_replay_recall.jsonl`)", "",
               "Recall@100 of each retrieval method against the ranker's top 100 over the full eligible set (2601.06873 section 5.2). Not like for like with the paper's Table 1.", "",
               table(["ground-truth ranker", "retrieval", "replay recall@100", "95% CI", "queries"],
                     [[r["ground_truth_ranker"], r["retrieval"], pct(r["replay_recall@100"]),
                       f"[{pct(r['ci95'][0])}, {pct(r['ci95'][1])}]", r["n_queries"]] for r in rr]), ""]
    # Service experiments: generic tables, every key shown.
    for name, title in (("m3_invariant", "M3: hard invariant replay"), ("m3_parity", "M3: ONNX parity"),
                        ("m3_exp5", "exp5: availability check (JMH)"), ("m3_latency", "exp9: end-to-end latency"),
                        ("m4_exp4", "exp4: IVF vs HNSW in Lucene under the update stream"),
                        ("m6_flexdates", "M6(b): flexible dates"), ("m6_diversity", "M6(a): diversity re-ranking"),
                        ("m5_position_bias", "exp10 (M5): position bias, SIMULATED")):
        rs = rows(name)
        if not rs:
            continue
        keys = [k for k in rs[0] if k not in ("machine", "load", "load_start", "load_end", "_file", "ts") and
                not isinstance(rs[0][k], (dict, list))]
        md += [f"## {title} (`{rs[0]['_file']}`)", "", f"Machine: {machine(rs[0])}.", "",
               table(keys, [[_fmt(r.get(k)) for k in keys] for r in rs]), ""]
    (ROOT / "NUMBERS.md").write_text("\n".join(md))
    print(f"wrote NUMBERS.md ({len(md)} lines)")


def _fmt(v):
    if isinstance(v, float):
        return f"{v:.4g}"
    return v


if __name__ == "__main__":
    main()
